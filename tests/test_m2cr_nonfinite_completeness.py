def _quadratic(diagonal=(1.0, 4.0, 9.0), center=None):
    matrix = np.diag(np.asarray(diagonal, dtype=np.float64))
    if center is None:
        center = np.zeros(3)
    center = np.asarray(center, dtype=np.float64)

    def g(u):
        delta = np.asarray(u, dtype=np.float64) - center
        return -0.5 * float(delta @ matrix @ delta)

    def grad(u):
        return -matrix @ (np.asarray(u, dtype=np.float64) - center)

    return g, grad


def _battery(nonfinite=False):
    references = (np.inf, -np.inf, np.nan) if nonfinite else (2.0, -3.0, 0.5)
    scale = np.inf if nonfinite else 3.0
    threshold = TOL_GRAD_ABS + TOL_GRAD_REL * scale
    return build_battery_record(
        [
            {
                "role": role,
                "fd_step": value,
                "reference_value": reference,
                "functional_value": value,
                "absolute_error": error,
                "threshold": threshold,
                "pass": False if nonfinite else True,
            }
            for role, reference, value, error in zip(
                ("ls", "os", "lv"),
                references,
                (np.nan, np.inf, -np.inf) if nonfinite else references,
                (np.inf, np.nan, -np.inf) if nonfinite else (0.0, 0.0, 0.0),
            )
        ]
    )


def _successful_optimizer():
    g, grad = _quadratic()
    result = gates.optimize_conditional_v2(
        lambda u: -g(u), lambda u: -grad(u), np.ones(3), -np.ones(3)
    )
    return result, build_two_start_optimizer_record(result, PERM)


def _normal_curvature():
    g, grad = _quadratic()
    result = gates.curvature_gate_v2(g, grad, np.zeros(3), STORAGE_ORDER)
    return result, build_curvature_record(result, PERM)


def _record_battery(monkeypatch):
    normal_opt_v2, normal_optimizer = _successful_optimizer()
    _normal_cur_v2, normal_curvature = _normal_curvature()
    mode_ref = build_warm_start_ref(
        {"kind": "mode_u"}, [0.0, 0.0, 0.0], "initial_mode_u"
    )
    previous_ref = build_warm_start_ref(
        {"kind": "accepted_node", "stage_id": "level0", "node_index": 0},
        [0.0, 0.0, 0.0],
        "carried_last_accepted_node",
    )
    current_ref = build_warm_start_ref(
        {"kind": "accepted_node", "stage_id": "level0", "node_index": 1},
        [0.0, 0.0, 0.0],
        "accepted_current_node",
    )
    normal_node = build_per_node_record(
        1,
        0.1,
        STORAGE_ORDER,
        mode_ref,
        current_ref,
        normal_optimizer,
        True,
        [0.0, 0.0, 0.0],
        _battery(),
        normal_curvature,
    )

    calls = 0

    def restart_warm(fun, x0, **kwargs):
        nonlocal calls
        calls += 1
        status = 2 if calls in {1, 3} else 0
        return OptimizeResult(
            x=np.zeros(3), status=status, success=status == 0, message="restart"
        )

    monkeypatch.setattr(gates, "minimize", restart_warm)
    restarted_v2 = gates.optimize_conditional_v2(
        lambda u: 0.0, lambda u: np.zeros(3), np.ones(3), -np.ones(3)
    )
    restarted_optimizer = build_two_start_optimizer_record(restarted_v2, PERM)

    def malformed_retry(fun, x0, **kwargs):
        return OptimizeResult(
            x=np.array([1.0, 2.0]), status=0, success=True, message="wrong shape"
        )

    monkeypatch.setattr(gates, "minimize", malformed_retry)
    indefinite_g, indefinite_grad = _quadratic((1.0, 4.0, -2.0))
    retried_v2 = gates.curvature_gate_v2(
        indefinite_g, indefinite_grad, np.zeros(3), STORAGE_ORDER
    )
    retried_curvature = build_curvature_record(retried_v2, PERM)
    fallback_node = build_per_node_record(
        2,
        0.2,
        STORAGE_ORDER,
        previous_ref,
        build_warm_start_ref(
            {"kind": "accepted_node", "stage_id": "level0", "node_index": 2},
            [0.0, 0.0, 0.0],
            "accepted_current_node",
        ),
        restarted_optimizer,
        True,
        [0.0, 0.0, 0.0],
        _battery(nonfinite=True),
        retried_curvature,
    )

    def nonfinite_attempt(fun, x0, **kwargs):
        return OptimizeResult(
            x=np.array([np.nan, np.inf, -np.inf]),
            status=0,
            success=True,
            message="all nonfinite",
        )

    monkeypatch.setattr(gates, "minimize", nonfinite_attempt)
    failed_v2 = gates.optimize_conditional_v2(
        lambda u: np.nan,
        lambda u: np.array([np.nan, np.inf, -np.inf]),
        np.ones(3),
        -np.ones(3),
    )
    failed_optimizer = build_two_start_optimizer_record(failed_v2, PERM)
    failed_node = build_per_node_record(
        3,
        0.3,
        STORAGE_ORDER,
        previous_ref,
        previous_ref,
        failed_optimizer,
        False,
        None,
    )
    assert normal_opt_v2["stop"] is False
    return [normal_node, fallback_node, failed_node]


_NUMERIC_REF_SHAPES = {
    "number_or_nonfinite": "",
    "vector_or_nonfinite": "[]",
    "matrix_or_nonfinite": "[][]",
    "canonical_vector3": "[]",
    "canonical_matrix3": "[][]",
    "finite_number": "",
    "count": "",
}


def _schema_numeric_paths(schema, path="$", seen=None):
    """Walk schema structure independently of all record builder code."""

    if seen is None:
        seen = set()
    paths = set()
    ref = schema.get("$ref")
    if ref is not None:
        assert ref.startswith("#/$defs/")
        name = ref.removeprefix("#/$defs/")
        if name in _NUMERIC_REF_SHAPES:
            paths.add(path + _NUMERIC_REF_SHAPES[name])
        elif (name, path) not in seen:
            paths |= _schema_numeric_paths(
                SCHEMA["$defs"][name], path, seen | {(name, path)}
            )
    if schema.get("type") in {"number", "integer"}:
        paths.add(path)
    const = schema.get("const")
    if isinstance(const, (int, float)) and not isinstance(const, bool):
        paths.add(path)
    for keyword in ("oneOf", "anyOf", "allOf"):
        for branch in schema.get(keyword, ()):
            paths |= _schema_numeric_paths(branch, path, seen)
    for name, subschema in schema.get("properties", {}).items():
        paths |= _schema_numeric_paths(subschema, f"{path}.{name}", seen)
    for index, subschema in enumerate(schema.get("prefixItems", ())):
        paths |= _schema_numeric_paths(subschema, f"{path}[{index}]", seen)
    items = schema.get("items")
    if isinstance(items, dict):
        paths |= _schema_numeric_paths(items, path + "[]", seen)
    return paths


def _emitted_numeric_leaves(value, path="$"):
    if is_nonfinite_sentinel(value):
        return {path}
    if isinstance(value, dict):
        result = set()
        for key, item in value.items():
            result |= _emitted_numeric_leaves(item, f"{path}.{key}")
        return result
    if isinstance(value, list):
        result = set()
        for index, item in enumerate(value):
            result |= _emitted_numeric_leaves(item, f"{path}[{index}]")
        return result
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return {path}
    return set()


def _pattern_matches(pattern, concrete):
    expression = re.escape(pattern).replace(r"\[\]", r"\[\d+\]")
    return re.fullmatch(expression, concrete) is not None


def test_schema_and_emitter_numeric_inventories_match_exactly(monkeypatch):
    schema_paths = _schema_numeric_paths({"$ref": "#/$defs/per_node_record"})
    emitted_paths = set()
    unmatched = set()
    for record in _record_battery(monkeypatch):
        for concrete in _emitted_numeric_leaves(record):
            matches = {path for path in schema_paths if _pattern_matches(path, concrete)}
            if not matches:
                unmatched.add(concrete)
            emitted_paths |= matches
    assert unmatched == set(), f"numeric fields emitted outside the schema: {unmatched}"
    assert emitted_paths == schema_paths, (
        f"schema-only={schema_paths - emitted_paths}; "
        f"emitter-only={emitted_paths - schema_paths}"
    )


