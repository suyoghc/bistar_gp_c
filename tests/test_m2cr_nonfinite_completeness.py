def test_full_optimizer_record_matches_handwritten_golden(monkeypatch):
    calls = 0

    def fixed_optimizer(fun, x0, **kwargs):
        nonlocal calls
        calls += 1
        candidate = (
            np.array([0.0, 1.0, 0.5])
            if calls == 1
            else np.array([1.0, 0.0, 0.5])
        )
        return OptimizeResult(
            x=candidate,
            status=0,
            success=True,
            message=f"fixed {calls}",
        )

    monkeypatch.setattr(gates, "minimize", fixed_optimizer)
    result = gates.optimize_conditional_v2(
        lambda u: np.inf if np.asarray(u)[0] == 0.0 else -0.5,
        lambda u: (
            np.array([0.0, -np.inf, np.nan])
            if np.asarray(u)[0] == 0.0
            else np.array([-0.0, -0.0, -0.0])
        ),
        np.ones(3),
        -np.ones(3),
    )
    assert result["restart_count"] == 0
    record = build_two_start_optimizer_record(result, PERM)
    validate_fragment(record, "#/$defs/two_start_optimizer_record")
    assert canonical_dumps(record) == GOLDEN_TWO_START_OPTIMIZER_RECORD


